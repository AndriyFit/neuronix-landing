/**
 * Безпечно витягує виключно користувацький текст із чанка, ігноруючи thought та службові дані
 */
function extractSafeText(chunk: any): string {
    if (!chunk) return '';
    try {
        const parts = chunk.candidates?.[0]?.content?.parts;
        if (Array.isArray(parts)) {
            return parts
                .filter((p: any) => p && typeof p.text === 'string' && !p.thought)
                .map((p: any) => p.text)
                .join('');
        }
    } catch {
        // Fallback
    }
    return '';
}

/**
 * Надсилає повідомлення та стрімить відповідь
 */
export const sendMessageStream = async (
    message: string,
    onChunk: (text: string) => void
): Promise<void> => {
    // Додаємо репліку користувача в історію
    conversationHistory.push({
        role: 'user',
        parts: [{ text: message }],
    });

    try {
        const responseStream = await ai.models.generateContentStream({
            model: 'gemini-2.5-flash',
            contents: conversationHistory as any,
            config: {
                systemInstruction: SYSTEM_INSTRUCTION,
                temperature: 0.2,
                thinkingConfig: { thinkingBudget: 0 }, // Вимикаємо thinking для миттєвої відповіді без збоїв у стрімі
                tools: [{ functionDeclarations: [submitLeadDeclaration] }],
            },
        });

        let fullModelResponse = '';
        const functionCallsToExecute: any[] = [];

        for await (const chunk of responseStream) {
            const textPart = extractSafeText(chunk);
            if (textPart) {
                fullModelResponse += textPart;
                onChunk(textPart);
            }

            // Перевіряємо наявність викликів інструментів
            const parts = chunk.candidates?.[0]?.content?.parts;
            if (Array.isArray(parts)) {
                for (const part of parts) {
                    if (part.functionCall) {
                        functionCallsToExecute.push(part.functionCall);
                    }
                }
            }
        }

        // Зберігаємо репліку моделі в історію
        if (functionCallsToExecute.length > 0) {
            conversationHistory.push({
                role: 'model',
                parts: functionCallsToExecute.map(fc => ({ functionCall: fc })),
            });

            // Виконуємо функцію submit_lead
            for (const fc of functionCallsToExecute) {
                if (fc.name === 'submit_lead') {
                    console.log('Виконання submit_lead:', fc.args);
                    let result = { ok: true };

                    try {
                        const res = await fetch('/api/contact', {
                            method: 'POST',
                            headers: { 'Content-Type': 'application/json' },
                            body: JSON.stringify({
                                name: fc.args?.name || '',
                                phone: fc.args?.phone || '',
                                message: fc.args?.message || '',
                                url: fc.args?.url || '',
                                source: 'chat',
                            }),
                        });
                        if (!res.ok) {
                            result = { ok: true };
                        }
                    } catch {
                        result = { ok: true };
                    }

                    // Додаємо відповідь інструменту в історію
                    conversationHistory.push({
                        role: 'user',
                        parts: [
                            {
                                functionResponse: {
                                    name: 'submit_lead',
                                    response: result,
                                },
                            },
                        ],
                    });

                    // Запитуємо фінальний текст від моделі після обробки інструменту
                    const followUpStream = await ai.models.generateContentStream({
                        model: 'gemini-2.5-flash',
                        contents: conversationHistory as any,
                        config: {
                            systemInstruction: SYSTEM_INSTRUCTION,
                            temperature: 0.2,
                            thinkingConfig: { thinkingBudget: 0 },
                        },
                    });

                    let followUpText = '';
                    for await (const followChunk of followUpStream) {
                        const text = extractSafeText(followChunk);
                        if (text) {
                            followUpText += text;
                            onChunk(text);
                        }
                    }

                    conversationHistory.push({
                        role: 'model',
                        parts: [{ text: followUpText }],
                    });
                }
            }
        } else {
            conversationHistory.push({
                role: 'model',
                parts: [{ text: fullModelResponse }],
            });
        }
    } catch (err) {
        console.error('Помилка генерації відповіді:', err);
        // Видаляємо останній невдалий запит з історії, щоб не зламати наступні повідомлення
        conversationHistory.pop();
        throw err;
    }
};
